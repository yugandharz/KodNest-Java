public class EscapeSequences {
    public static void main(String[] args) {
        System.out.println("my name is \n yugandhar\n");
        /* 
        output = my name is 
                   yugandhar
        */
        System.out.println("my favorite:\tjava");
        /*
        output = my favorite:    java
         */
        System.out.println("i want to be a \"java developer\"");
        /*
        output = i want to be a "java developer"
         */
        System.out.println("my kodnest file loctaion:c:\\user\\Desktop\\Kodnest");

    }
    
}
